#!/usr/bin/env bash
set -euo pipefail

[[ $# == 5 ]] || {
    echo 'Usage: remote-scheduler.sh BUNDLE WORK_ROOT MANIFEST PARALLEL OUTPUT_DIR' >&2
    exit 2
}

BUNDLE=$1
WORK_ROOT=$2
MANIFEST=$3
PARALLEL=$4
OUTPUT_DIR=$5

[[ $BUNDLE == /* && $WORK_ROOT == /* && $MANIFEST == /* && $OUTPUT_DIR == /* ]] || {
    echo 'All scheduler paths must be absolute' >&2
    exit 2
}
[[ $PARALLEL =~ ^[1-9][0-9]*$ ]] || { echo 'PARALLEL must be positive' >&2; exit 2; }
[[ -x $BUNDLE/tests/patch-runner/test-patch.sh ]] || { echo 'Missing staged patch runner' >&2; exit 2; }
[[ -x $BUNDLE/build/smithproxy ]] || { echo 'Missing staged smithproxy binary' >&2; exit 2; }
[[ -f $BUNDLE/coordinator-config.sh ]] || { echo 'Missing coordinator config' >&2; exit 2; }
[[ -f $MANIFEST ]] || { echo "Missing manifest: $MANIFEST" >&2; exit 2; }

# This file is generated by test-patch.sh exclusively with printf %q values.
# shellcheck source=/dev/null
source "$BUNDLE/coordinator-config.sh"

mkdir -p "$OUTPUT_DIR" "$WORK_ROOT/sections"
TIMING_HISTORY=${PATCH_TEST_TIMING_HISTORY:-/var/tmp/smithproxy-patch-runner-history/$(id -u)/section-durations.tsv}
[[ $TIMING_HISTORY == /* ]] || { echo 'PATCH_TEST_TIMING_HISTORY must be absolute' >&2; exit 2; }
TIMING_HISTORY_DIR=$(dirname "$TIMING_HISTORY")
if [[ $TIMING_HISTORY == /var/tmp/smithproxy-patch-runner-history/* ]]; then
    mkdir -p /var/tmp/smithproxy-patch-runner-history
    chmod 1777 /var/tmp/smithproxy-patch-runner-history
fi
mkdir -p "$TIMING_HISTORY_DIR"
touch "$TIMING_HISTORY"
exec 8>"$TIMING_HISTORY.lock"
flock -s 8
TIMING_SNAPSHOT=$OUTPUT_DIR/timing-history-before.tsv
cp "$TIMING_HISTORY" "$TIMING_SNAPSHOT"
flock -u 8

# Longest-processing-time first minimizes the tail of a fixed worker pool.
# Unknown sections keep their manifest order behind sections with history.
mapfile -t JOBS < <(
    awk -F '\t' 'FILENAME == ARGV[1] { duration[$1]=$2; next }
        NF { printf "%012d\t%09d\t%s\n", duration[$2]+0, FNR, $0 }' \
        "$TIMING_SNAPSHOT" "$MANIFEST" |
        sort -t $'\t' -k1,1nr -k2,2n |
        cut -f3-
)
{
    printf 'job\tsection\testimated_ms\n'
    for line in "${JOBS[@]}"; do
        IFS=$'\t' read -r job section _ <<< "$line"
        estimate=$(awk -F '\t' -v wanted="$section" '$1 == wanted {print $2; exit}' "$TIMING_SNAPSHOT")
        printf '%s\t%s\t%s\n' "$job" "$section" "${estimate:-unknown}"
    done
} > "$OUTPUT_DIR/schedule.tsv"

run_section() {
    local line=$1 job section seeds child_rc started_ns finished_ns duration_ms
    local -a fuzz_env=()
    IFS=$'\t' read -r job section seeds <<< "$line"
    [[ $job =~ ^[A-Za-z0-9._-]+$ ]] || { echo "Invalid job: $job" >&2; return 2; }
    [[ $section =~ ^[A-Za-z0-9._-]+$ ]] || { echo "Invalid section: $section" >&2; return 2; }
    if [[ $section == fuzz.* ]]; then
        [[ -n $seeds && $seeds != - ]] || { echo "Missing fuzz seeds for $section" >&2; return 2; }
        fuzz_env=(--env "FUZZ_SEEDS=$seeds" --env "FUZZ_LEVEL=$PATCH_RUN_FUZZ_LEVEL" --env FUZZ_SCATTER=1)
    fi

    started_ns=$(date +%s%N)
    set +e
    if [[ $section == lifecycle ]]; then
        mkdir -p "$WORK_ROOT/sections/$job"
        unshare --user --map-root-user --keep-caps --mount --propagation private --net \
            "$BUNDLE/tests/patch-runner/run-proxy-nightmare-lifecycle.sh" \
            "$WORK_ROOT/sections/$job/results" \
            python3 "$BUNDLE/tests/patch-runner/test-proxy-nightmare-lifecycle.py" \
            --source "$BUNDLE" --smithproxy "$BUNDLE/build/smithproxy" \
            --monitor "$BUNDLE/build/smithproxy-cpu-monitor" \
            --proxy-nightmare "$BUNDLE/proxy-nightmare" \
            > "$OUTPUT_DIR/$job.log" 2>&1
    else
        env PATCH_TEST_ROOT_OVERRIDE="$BUNDLE" \
            PATCH_TEST_COMMIT_OVERRIDE="$PATCH_RUN_COMMIT" \
            PATCH_TEST_BRANCH_OVERRIDE="$PATCH_RUN_BRANCH" \
            PATCH_TEST_DIRTY_OVERRIDE="$PATCH_RUN_DIRTY" \
            CURL_HTTP3_PREFIX="$BUNDLE/curl-http3" \
            QUIC_PYTHON_PREFIX="$BUNDLE/quic-python" \
            "$BUNDLE/tests/patch-runner/test-patch.sh" sanity \
            --skip-build --build-dir "$BUNDLE/build" --shared-binary "$BUNDLE/build/smithproxy" \
            --quiet --worker --local --suite "$section" --dir "$WORK_ROOT/sections/$job" \
            "${PATCH_RUN_ENV_ARGS[@]}" "${fuzz_env[@]}" > "$OUTPUT_DIR/$job.log" 2>&1
    fi
    child_rc=$?
    set -e
    finished_ns=$(date +%s%N)
    duration_ms=$(( (finished_ns - started_ns) / 1000000 ))
    printf '%s\n' "$child_rc" > "$OUTPUT_DIR/$job.rc"
    printf '%s\n' "$duration_ms" > "$OUTPUT_DIR/$job.duration-ms"
    echo "SECTION DONE: $job suite=$section rc=$child_rc duration_ms=$duration_ms"
    return 0
}

declare -A PID_JOB=()
next=0
active=0
while ((next < ${#JOBS[@]} || active > 0)); do
    while ((next < ${#JOBS[@]} && active < PARALLEL)); do
        line=${JOBS[$next]}
        job=${line%%$'\t'*}
        echo "SECTION START: $job"
        run_section "$line" &
        pid=$!
        PID_JOB[$pid]=$job
        ((next += 1, active += 1))
    done
    if ((active > 0)); then
        done_pid=
        wait -n -p done_pid || true
        if [[ -n $done_pid && -n ${PID_JOB[$done_pid]:-} ]]; then
            : $((active -= 1))
            unset 'PID_JOB[$done_pid]'
        fi
    fi
done

# Store the latest complete observation for each section. One exclusive lock
# and an atomic rename keep concurrent top-level runs from corrupting history.
TIMING_UPDATES=$OUTPUT_DIR/timing-updates.tsv
: > "$TIMING_UPDATES"
for line in "${JOBS[@]}"; do
    IFS=$'\t' read -r job section _ <<< "$line"
    printf '%s\t%s\t%s\n' "$section" "$(<"$OUTPUT_DIR/$job.duration-ms")" "$(date -u +%FT%TZ)" \
        >> "$TIMING_UPDATES"
done
flock -x 8
TIMING_TEMP=$TIMING_HISTORY.tmp.$$
awk -F '\t' 'NF >= 2 { latest[$1]=$0 } END { for (section in latest) print latest[section] }' \
    "$TIMING_HISTORY" "$TIMING_UPDATES" | sort > "$TIMING_TEMP"
chmod 0644 "$TIMING_TEMP"
mv "$TIMING_TEMP" "$TIMING_HISTORY"
flock -u 8

for line in "${JOBS[@]}"; do
    job=${line%%$'\t'*}
    [[ -f $OUTPUT_DIR/$job.rc ]] || {
        echo "Scheduler lost result for $job" >&2
        exit 1
    }
done

# One archive per batch keeps result retrieval to one SCP connection. Copy the
# report metadata needed by the coordinator, but leave per-case lab artifacts
# on the execution target. Corpus and fuzz runs can create thousands of tiny
# files there, which needlessly consume coordinator inodes when every section
# passed.
relative_output=${OUTPUT_DIR#"$WORK_ROOT"/}
mapfile -t RESULT_DIRS < <(find "$WORK_ROOT/sections" -mindepth 2 -maxdepth 2 -type d -name results -printf '%P\n' | sed 's#^#sections/#' | sort)
tar --exclude='*/lab-results' --exclude='*/lab-results/*' \
    -C "$WORK_ROOT" -cf "$OUTPUT_DIR.tar" "$relative_output" "${RESULT_DIRS[@]}"
chmod 0644 "$OUTPUT_DIR.tar"
