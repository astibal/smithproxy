void decode_print(std::vector<uint8_t>& vec) {
    HPACK::decoder_t dec;

    if (dec.decode(vec)) {
        for (auto& [ hdr, vlist ] : dec.headers()) {

            for(auto const& hdr_elem: vlist)
                std::cout << "Frame: header/" << hdr << ": " << hdr_elem << "\n";
        }
    } else {
        std::cout << "Frame: hpack decode error";
    }
}

